/**
 * D1 schema snapshots (SPEC §6.2).
 *
 * Applies migrations, in deploy order, to an empty in-memory SQLite database
 * (D1 is SQLite) and renders the resulting schema as normalized SQL. The snapshot
 * is committed; CI regenerates it and fails when it differs, so every schema change
 * arrives with a migration and shows up as a readable diff in the PR.
 */
import { DatabaseSync } from 'node:sqlite';
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { basename, join } from 'node:path';

export interface MigrationSource {
	/** Label used in the snapshot header. */
	label: string;
	dir: string;
	/** Which files in `dir` are migrations (wrangler: every .sql file). */
	pattern: RegExp;
}

export function listMigrations(source: MigrationSource): string[] {
	if (!existsSync(source.dir)) return [];
	return readdirSync(source.dir)
		.filter((f) => source.pattern.test(f))
		.sort()
		.map((f) => join(source.dir, f));
}

function normalizeSql(sql: string): string {
	return sql
		.replace(/--[^\n]*/g, '')
		.replace(/\s+/g, ' ')
		.replace(/\(\s+/g, '(')
		.replace(/\s+\)/g, ')')
		.replace(/\s*,\s*/g, ', ')
		.trim();
}

export function buildSchema(sources: MigrationSource[]): string {
	const db = new DatabaseSync(':memory:');
	const applied: string[] = [];
	try {
		for (const source of sources) {
			for (const file of listMigrations(source)) {
				try {
					db.exec(readFileSync(file, 'utf8'));
				} catch (error) {
					throw new Error(`${source.label}/${basename(file)} failed to apply: ${(error as Error).message}`);
				}
				applied.push(`${source.label}/${basename(file)}`);
			}
		}
		const rows = db
			.prepare(
				`SELECT type, name, tbl_name, sql FROM sqlite_master
				 WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '_cf_%' AND name <> 'd1_migrations'
				 ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'view' THEN 2 ELSE 3 END, tbl_name, name`
			)
			.all() as { type: string; name: string; tbl_name: string; sql: string }[];
		const header = [
			'-- GENERATED by scripts/release/schema-snapshot.ts. Do not edit by hand.',
			'-- Schema after applying, in order:',
			...applied.map((a) => `--   ${a}`),
			'',
		];
		return [...header, ...rows.map((r) => `${normalizeSql(r.sql)};`), ''].join('\n');
	} finally {
		db.close();
	}
}
