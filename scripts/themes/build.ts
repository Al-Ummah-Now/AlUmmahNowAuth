/**
 * Auth theme packages: bundles the built-in packages and writes the x-auth schema.
 *   node --experimental-strip-types scripts/themes/build.ts          (write)
 *   node --experimental-strip-types scripts/themes/build.ts --check  (exit 1 when stale or invalid)
 * Built-in packages live in packages/ui/src/auth-theme/themes/<id>/ (theme.json + assets/), in the
 * platform's theme package format v1 (packages/ui/src/theme-packages).
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SCHEMA } from '../../packages/ui/src/theme-packages/schema.generated.ts';
import { AUTH_EXTENSION_SCHEMA, assetTypeFor, formatIssues, validateTheme } from '../../packages/ui/src/auth-theme/validate.ts';

const root = fileURLToPath(new URL('../..', import.meta.url));
const dir = join(root, 'packages/ui/src/auth-theme');
const TEXT = /\.svg$/;

const pick = (names: string[]) => Object.fromEntries(names.map((n) => [n, (SCHEMA as { $defs: Record<string, unknown> }).$defs[n]]));

function walk(d: string, prefix = ''): string[] {
	return readdirSync(d).flatMap((n) => (statSync(join(d, n)).isDirectory() ? walk(join(d, n), `${prefix}${n}/`) : [`${prefix}${n}`]));
}

export function build(): { files: Record<string, string>; problems: string[] } {
	const problems: string[] = [];
	const vendored = JSON.parse(readFileSync(join(root, 'packages/ui/src/theme-packages/theme-package.v1.schema.json'), 'utf8'));
	if (JSON.stringify(vendored) !== JSON.stringify(SCHEMA)) problems.push('theme-packages: schema.generated.ts and theme-package.v1.schema.json disagree');

	const themesDir = join(dir, 'themes');
	const ids = readdirSync(themesDir).filter((n) => existsSync(join(themesDir, n, 'theme.json'))).sort();
	const packages: Record<string, unknown> = {};
	const blobs: Record<string, unknown> = {};
	for (const id of ids) {
		const theme = JSON.parse(readFileSync(join(themesDir, id, 'theme.json'), 'utf8'));
		delete theme.$schema;
		const assetsDir = join(themesDir, id, 'assets');
		const assets: Record<string, unknown> = {};
		const bytes: Record<string, Uint8Array> = {};
		for (const rel of existsSync(assetsDir) ? walk(assetsDir).sort() : []) {
			const data = readFileSync(join(assetsDir, rel));
			const path = `assets/${rel}`;
			const type = assetTypeFor(path);
			if (!type) problems.push(`${id}: ${path} is not an allowed asset`);
			const hash = createHash('sha256').update(data).digest('hex');
			bytes[path] = new Uint8Array(data);
			assets[path] = { hash, type, size: data.length };
			blobs[hash] = { type, ...(TEXT.test(rel) ? { text: data.toString('utf8') } : { base64: data.toString('base64') }) };
		}
		const v = validateTheme(theme, { files: bytes, builtIn: true });
		if (theme.id !== id) problems.push(`${id}: theme.json id is ${theme.id}`);
		if (v.errors.length || v.contrast.length) problems.push(`${id}: ${formatIssues([...v.errors, ...v.contrast])}`);
		if (v.warnings.length) problems.push(`${id}: ${formatIssues(v.warnings)}`);
		packages[id] = { theme, assets };
	}
	const generated =
		`// Generated by scripts/themes/build.ts from packages/ui/src/auth-theme/themes/. Do not edit.\n` +
		`import type { BuiltinBlob, BuiltinPackage } from './builtin.ts';\n` +
		`export const BUILTIN_PACKAGES: Record<string, BuiltinPackage> = ${JSON.stringify(packages)};\n` +
		`export const BUILTIN_BLOBS: Record<string, BuiltinBlob> = ${JSON.stringify(blobs)};\n`;
	return {
		files: {
			[join(dir, 'builtin.generated.ts')]: generated,
			[join(dir, 'x-auth.schema.json')]: `${JSON.stringify({ ...AUTH_EXTENSION_SCHEMA, $defs: pick(['localized', 'cssValue', 'imageAsset']) }, null, 2)}\n`,
		},
		problems,
	};
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
	const { files, problems } = build();
	const check = process.argv.includes('--check');
	let stale = 0;
	for (const [file, content] of Object.entries(files)) {
		const current = existsSync(file) ? readFileSync(file, 'utf8') : '';
		if (current === content) continue;
		stale++;
		if (check) process.stderr.write(`stale: ${file} (run pnpm themes:build)\n`);
		else writeFileSync(file, content);
	}
	for (const p of problems) process.stderr.write(`invalid: ${p}\n`);
	if (problems.length || (check && stale)) process.exit(1);
	process.stdout.write(check ? 'Theme files are up to date.\n' : `Wrote ${stale} theme file(s).\n`);
}
