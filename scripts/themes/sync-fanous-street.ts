/**
 * Vendors the Fanous lantern street (the shared module every Al Ummah Now app includes:
 * AlUmmahNow `packages/fanous-tokens/street`) into Auth at a pinned commit, with hashes.
 *
 *   node --experimental-strip-types scripts/themes/sync-fanous-street.ts --ref <40-char sha>   (fetch, rewrite)
 *   node --experimental-strip-types scripts/themes/sync-fanous-street.ts                       (re-fetch the locked ref)
 *   node --experimental-strip-types scripts/themes/sync-fanous-street.ts --check               (offline: files == lock)
 *
 * The monorepo is public: files come from raw.githubusercontent.com with no token.
 *
 * Writes packages/ui/src/fanous-street/:
 *   fanous-street.js, fanous-street.d.ts, fanous-street.css   the module as is, under a header
 *   street.generated.ts                                        the JS and CSS as strings, so the
 *                                                              three workers serve them same-origin
 *   fanous-street.lock.json                                    repo, ref, source and output hashes
 * The design record is AlUmmahNow docs/design/FAWANEES-STREET.md.
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const REPO = 'Al-Ummah-Now/AlUmmahNow';
export const SOURCES = {
	js: 'packages/fanous-tokens/street/fanous-street.js',
	dts: 'packages/fanous-tokens/street/fanous-street.d.ts',
	css: 'packages/fanous-tokens/street/fanous-street.css',
} as const;
type Kind = keyof typeof SOURCES;
export const DIR = 'packages/ui/src/fanous-street';
export const OUT: Record<Kind, string> = {
	js: `${DIR}/fanous-street.js`,
	dts: `${DIR}/fanous-street.d.ts`,
	css: `${DIR}/fanous-street.css`,
};
export const TS_OUT = `${DIR}/street.generated.ts`;
export const LOCK = `${DIR}/fanous-street.lock.json`;

export interface Lock {
	repo: string;
	ref: string;
	/** sha256 of each source file at `ref`, by monorepo path. */
	sources: Record<string, string>;
	/** sha256 of each written file, by repo path. */
	outputs: Record<string, string>;
}

export const sha256 = (s: string) => createHash('sha256').update(s).digest('hex');

/** A vendored file: the source as is, under a generated-file header. */
export function vendorFile(source: string, kind: Kind, ref: string): string {
	const header = `Generated by scripts/themes/sync-fanous-street.ts from ${REPO}@${ref}:${SOURCES[kind]}. Do not edit.`;
	return `${kind === 'css' ? `/* ${header} */` : `// ${header}`}\n${source}`;
}

/** The TS module the workers import: the browser files as strings, with a short content hash for cache-busting URLs. */
export function generatedTs(js: string, css: string, ref: string): string {
	const json = (s: string) => JSON.stringify(s).replace(/</g, '\\u003c');
	return (
		`// Generated by scripts/themes/sync-fanous-street.ts from ${REPO}@${ref}. Do not edit.\n` +
		`export const STREET_REF = ${JSON.stringify(ref)};\n` +
		`export const STREET_JS = ${json(js)};\n` +
		`export const STREET_CSS = ${json(css)};\n` +
		`export const STREET_HASH = ${JSON.stringify(sha256(js + css).slice(0, 12))};\n`
	);
}

/** Every output for these sources. */
export function buildOutputs(sources: Record<Kind, string>, ref: string): Record<string, string> {
	const files: Record<Kind, string> = {
		js: vendorFile(sources.js, 'js', ref),
		dts: vendorFile(sources.dts, 'dts', ref),
		css: vendorFile(sources.css, 'css', ref),
	};
	return { [OUT.js]: files.js, [OUT.dts]: files.dts, [OUT.css]: files.css, [TS_OUT]: generatedTs(files.js, files.css, ref) };
}

/** Problems with the files on disk against the lock (empty when they match). */
export function checkFiles(root: string): string[] {
	const lockPath = join(root, LOCK);
	if (!existsSync(lockPath)) return [`${LOCK} is missing`];
	const lock = JSON.parse(readFileSync(lockPath, 'utf8')) as Lock;
	const problems: string[] = [];
	if (!/^[0-9a-f]{40}$/.test(lock.ref)) problems.push(`${LOCK}: ref must be a 40-character commit`);
	for (const path of [...Object.values(OUT), TS_OUT]) {
		const file = join(root, path);
		if (!existsSync(file)) { problems.push(`${path} is missing`); continue; }
		if (sha256(readFileSync(file, 'utf8')) !== lock.outputs[path]) problems.push(`${path} differs from ${LOCK} (run the sync, never edit it)`);
	}
	return problems;
}

async function fetchSource(path: string, ref: string): Promise<string> {
	const url = `https://raw.githubusercontent.com/${REPO}/${ref}/${path}`;
	const res = await fetch(url);
	if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
	return res.text();
}

async function main() {
	const root = fileURLToPath(new URL('../..', import.meta.url));
	const args = process.argv.slice(2);
	if (args.includes('--check')) {
		const problems = checkFiles(root);
		for (const p of problems) process.stderr.write(`fanous-street: ${p}\n`);
		if (problems.length) process.exit(1);
		process.stdout.write('Fanous street files match the lock.\n');
		return;
	}
	const at = args.indexOf('--ref');
	const ref = at >= 0 ? args[at + 1] : (JSON.parse(readFileSync(join(root, LOCK), 'utf8')) as Lock).ref;
	if (!ref || !/^[0-9a-f]{40}$/.test(ref)) throw new Error('--ref must be a 40-character commit sha');
	const sources = {} as Record<Kind, string>;
	for (const kind of Object.keys(SOURCES) as Kind[]) sources[kind] = await fetchSource(SOURCES[kind], ref);
	const outputs = buildOutputs(sources, ref);
	for (const [path, text] of Object.entries(outputs)) writeFileSync(join(root, path), text);
	const lock: Lock = {
		repo: REPO,
		ref,
		sources: Object.fromEntries((Object.keys(SOURCES) as Kind[]).map((k) => [SOURCES[k], sha256(sources[k])])),
		outputs: Object.fromEntries(Object.entries(outputs).map(([p, t]) => [p, sha256(t)])),
	};
	writeFileSync(join(root, LOCK), `${JSON.stringify(lock, null, 2)}\n`);
	process.stdout.write(`Vendored the Fanous street at ${ref}.\n`);
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1]);
if (isMain) {
	main().catch((err: unknown) => {
		process.stderr.write(`${err instanceof Error ? err.message : String(err)}\n`);
		process.exit(1);
	});
}
