/** The browser tab title: "<page> - Al Ummah Now Admin", or before it a name (a role, a theme). */
export function pageTitle(key: TitleKey, lang: AdminLang, name?: string): string {
  const t = TITLES[lang];
  const page = key in t ? t[key as keyof typeof t] : shellCopy(lang).nav[key as NavKey];
  return [name, page, t.admin].filter(Boolean).join(" - ");
}

