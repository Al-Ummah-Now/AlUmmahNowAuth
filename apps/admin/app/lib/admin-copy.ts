/** Noun forms after an Arabic number: 1, 2, 3–10, 11–99 (accusative), 100s and thousands (genitive). */
export interface ArNoun {
  one: string;
  two: string;
  few: string;
  many: string;
  /** After 100, 200 … and after «ألف» / «م»: the genitive singular. */
  hundreds: string;
}

/**
 * A count with its noun. Counts from 1,000 are compact and cut (never rounded): "1.2K users",
 * «١٫٢ ألف مستخدم». Below that the exact number: "1 user", «مستخدم واحد», «٣ مستخدمين»,
 * «١١ مستخدمًا», «١٠٠ مستخدم».
 */
export function countOf(n: number, lang: AdminLang, en: [one: string, many: string], ar: ArNoun): string {
  const safe = Number.isFinite(n) ? Math.trunc(n) : 0;
  if (lang !== "ar") return `${safe >= 1000 ? formatCompact(safe, "en") : formatNumber(safe, "en")} ${safe === 1 ? en[0] : en[1]}`;
  if (safe >= 1000) return `${formatCompact(safe, "ar", { beforeNoun: true })} ${ar.hundreds}`;
  if (safe === 1) return ar.one;
  if (safe === 2) return ar.two;
  const num = formatNumber(safe, "ar");
  const rest = safe % 100;
  if (rest >= 3 && rest <= 10) return `${num} ${ar.few}`;
  if (rest >= 11) return `${num} ${ar.many}`;
  // 0, 100, 101, 102 …: «٠ مستخدم», «١٠٠ مستخدم», «١٠١ مستخدم»
  return `${num} ${ar.hundreds}`;
}

