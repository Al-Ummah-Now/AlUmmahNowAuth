/**
 * The words of the admin's Users, user Passkeys, Sessions, OAuth clients and Audit pages, in
 * English and Arabic (?lang=ar, the admin's language switch). Numbers go through the shared
 * formatter, so Arabic shows Eastern Arabic (Hindi) numerals ٠–٩ (packages/ui/src/format.ts).
 * Arabic terms follow the shell (lib/shell-copy.ts): «المستخدمون», «الأدوار», «الجلسات»,
 * «عملاء OAuth», «سجل التدقيق», «مفاتيح المرور». Protocol names (OAuth, OpenID, grant and
 * scope values, event types) stay as they are: they are code.
 */
import { formatNumber } from "../../../../packages/ui/src/format.ts";
import type { AdminLang } from "./deletion-copy";

const n = (value: number, lang: AdminLang) => formatNumber(value, lang);

/** Arabic count wording: 1, 2, 3–10, 11+ (the noun changes with the number). */
function arCount(value: number, one: string, two: string, few: string, many: string): string {
  if (value === 1) return one;
  if (value === 2) return two;
  const num = n(value, "ar");
  return value >= 3 && value <= 10 ? `${num} ${few}` : `${num} ${many}`;
}

